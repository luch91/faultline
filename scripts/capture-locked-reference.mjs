import { chromium, expect } from '@playwright/test';
import { mkdir, copyFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const base = process.env.FAULTLINE_CAPTURE_URL ?? 'http://127.0.0.1:5173';
const output = process.env.FAULTLINE_CAPTURE_DIR ?? '../faultline-visual-evidence';
await mkdir(output, { recursive: true });
const browser = await chromium.launch(process.env.FAULTLINE_CHROMIUM_PATH ? { executablePath: process.env.FAULTLINE_CHROMIUM_PATH } : {});
const errors = [];
const context = await browser.newContext({ viewport: { width: 750, height: 512 }, deviceScaleFactor: 1 });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
if (base.startsWith('http://127.0.0.1')) await page.route('**/api/v1/**', route => route.continue({ headers: { ...route.request().headers(), 'CF-Connecting-IP': `reference-capture-${crypto.randomUUID()}` } }));
const settle = async () => { await expect(page.getByLabel('Evaluation outcome')).toHaveText('SAFE_EXECUTION', { timeout: 30_000 }); await page.waitForTimeout(200); await page.mouse.move(749, 511); };
for (const [name, t] of process.env.FAULTLINE_CAPTURE_PHASE === 'interaction' ? [] : [['01-overview', 0], ['02-focus-selection', 1.9], ['03-line-formation', 2.8], ['04-radial-expansion', 3.5], ['05-focused-relationships', 5], ['06-expanded-analytics', 8], ['07-network-return', 11], ['08-overview-approach', 13.5], ['09-returned-overview', 17], ['10-final-transition', 18.5]]) {
  await page.goto(`${base}/?motion=${t}`); await settle();
  await page.screenshot({ path: join(output, `${name}.png`) });
}
await page.goto(`${base}/?motion=5`); await settle();
await page.getByRole('button', { name: 'Flat view', exact: true }).click();
await page.getByRole('button', { name: 'Workflow tools', exact: true }).click();
let dialog = page.getByRole('dialog', { name: 'Workflow tools' });
await dialog.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('human-approval');
await dialog.getByRole('button', { name: 'Apply intervention', exact: true }).click();
await expect(page.locator('.evaluation-outcome')).toHaveText('UNSAFE_EXECUTION');
await page.getByRole('button', { name: 'Close panel' }).click();
await page.getByRole('button', { name: 'Reset perspective' }).click();
await page.mouse.move(749, 511); await page.screenshot({ path: join(output, '11-unsafe-counterfactual.png') });
await page.getByRole('button', { name: 'Flat view', exact: true }).click();
await page.getByRole('button', { name: 'Workflow tools', exact: true }).click();
dialog = page.getByRole('dialog', { name: 'Workflow tools' });
await dialog.getByRole('button', { name: 'Test safeguard', exact: true }).click();
await expect(page.locator('.evaluation-outcome')).toHaveText('SAFE_BLOCK');
await page.getByRole('button', { name: 'Close panel' }).click();
await page.getByRole('button', { name: 'Reset perspective' }).click();
await page.mouse.move(749, 511); await page.screenshot({ path: join(output, '12-verified-safeguard.png') });
await page.setViewportSize({width:360,height:780});
await page.getByRole('button', {name:'Workflow tools',exact:true}).click();
await page.screenshot({path:join(output,'14-mobile-investigation.png')});
await context.close();
const recording = await browser.newContext({ viewport: { width: 750, height: 512 }, deviceScaleFactor: 1, recordVideo: { dir: output, size: { width: 750, height: 512 } } });
const motionPage = await recording.newPage();
motionPage.on('pageerror', error => errors.push(error.message));
if (base.startsWith('http://127.0.0.1')) await motionPage.route('**/api/v1/**', route => route.continue({ headers: { ...route.request().headers(), 'CF-Connecting-IP': `recording-${crypto.randomUUID()}` } }));
await motionPage.goto(base); await expect(motionPage.getByLabel('Evaluation outcome')).toHaveText('SAFE_EXECUTION', { timeout: 30_000 });
await motionPage.getByRole('button', { name: 'Play presentation', exact: true }).click();
await motionPage.mouse.move(749, 511);
await motionPage.waitForTimeout(19100);
const finalTime = await motionPage.locator('.reference-stage').getAttribute('data-motion-time');
const video = motionPage.video(); await recording.close();
if (video) await copyFile(await video.path(), join(output, '13-real-browser-motion.webm'));
await browser.close();
await writeFile(join(output, 'browser-capture.json'), JSON.stringify({ base, viewport: { width: 750, height: 512 }, deviceScaleFactor: 1, finalTime, pageErrors: errors, capturedAt: new Date().toISOString(), sourceFramesEmbedded: false }, null, 2));
if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`);
console.log(JSON.stringify({ output, finalTime, pageErrors: errors }));
